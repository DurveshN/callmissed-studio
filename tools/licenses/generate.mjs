// Writes THIRD_PARTY_LICENSES.md: every npm package that ships inside the app (main-process
// dependencies, the libraries Vite bundles into the renderer, and all of their dependencies),
// plus Electron, the bundled fonts and the downloadable models. Run: node tools/licenses/generate.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..', '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
// devDependencies whose code ends up in the renderer bundle.
const BUNDLED = [
  'react',
  'react-dom',
  'react-konva',
  'konva',
  'pdfjs-dist',
  'zustand',
  'immer',
  'lucide-react'
]

const seen = new Map()
function visit(name) {
  if (seen.has(name)) return
  const dir = join(root, 'node_modules', name)
  if (!existsSync(join(dir, 'package.json'))) return
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url
  seen.set(name, {
    version: meta.version,
    license: meta.license ?? meta.licenses?.map((l) => l.type).join(' OR ') ?? 'see package',
    url: (repo ?? meta.homepage ?? `https://www.npmjs.com/package/${name}`)
      .replace(/^git\+/, '')
      .replace(/^(git|ssh):\/\/(git@)?/, 'https://')
      .replace(/^git@github\.com:/, 'https://github.com/')
      .replace(/^(github:)?([\w.-]+\/[\w.-]+)$/, 'https://github.com/$2')
      .replace(/\.git$/, '')
  })
  for (const dep of Object.keys(meta.dependencies ?? {})) visit(dep)
}
for (const name of [...Object.keys(pkg.dependencies), ...BUNDLED]) visit(name)

const electron = JSON.parse(readFileSync(join(root, 'node_modules/electron/package.json'), 'utf8'))
const manifest = JSON.parse(readFileSync(join(root, 'resources/models.manifest.json'), 'utf8'))
const fontsDir = join(root, 'src/renderer/public/fonts')
const fonts = readdirSync(fontsDir, { withFileTypes: true }).filter((d) => d.isDirectory())

const rows = [...seen].sort(([a], [b]) => a.localeCompare(b))
const md = `# Third-party licences

CallMissed Studio is MIT-licensed (see [LICENSE](LICENSE)). It ships or downloads the following
third-party software, fonts and models under their own licences. Generated by
\`node tools/licenses/generate.mjs\`; do not edit by hand.

## Runtime

- [Electron](https://github.com/electron/electron) ${electron.version}: MIT. Electron includes
  Chromium and Node.js; their licences are in \`LICENSES.chromium.html\` and \`LICENSE.electron.txt\`
  in the installed app's folder.

## npm packages in the app (${rows.length})

| Package | Version | Licence | Source |
| --- | --- | --- | --- |
${rows.map(([name, p]) => `| ${name} | ${p.version} | ${p.license} | ${p.url} |`).join('\n')}

## Fonts

Bundled from [google/fonts](https://github.com/google/fonts), unmodified, under the SIL Open Font
License 1.1. Each family's \`OFL.txt\` is next to its files in \`src/renderer/public/fonts/\`.

${fonts.map((d) => `- ${d.name}`).join('\n')}

## AI models (downloaded on first use, not in the installer)

| Model pack | Licence | Source |
| --- | --- | --- |
${manifest.packs.map((p) => `| ${p.name}: ${p.description} | ${p.license} | ${p.source} |`).join('\n')}
`
writeFileSync(join(root, 'THIRD_PARTY_LICENSES.md'), md)
console.log(
  `THIRD_PARTY_LICENSES.md: ${rows.length} packages, ${fonts.length} fonts, ${manifest.packs.length} models`
)
